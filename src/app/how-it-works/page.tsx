function StorageBars({
  sizes,
  indexes,
}: {
  sizes: { relname: string; bytes: number; n_live_tup: number }[];
  indexes: { name: string; bytes: number }[];
}) {
  const items = [
    ...sizes.map((s) => ({ label: s.relname, bytes: s.bytes })),
    ...indexes.map((i) => ({ label: i.name.replace(/^chunks_/, ""), bytes: i.bytes })),
  ].sort((a, b) => b.bytes - a.bytes);

  const W = 720;
  const rowH = 26;
  const padL = 176;
  const padR = 84;
  const H = items.length * rowH + 24;
  const max = Math.max(...items.map((i) => i.bytes));

  return (
    <svg
      className="chart"
      viewBox={`0 0 ${W} ${H}`}
      role="img"
      aria-label={`On-disk size by relation and index. Largest is ${items[0].label} at ${formatBytes(items[0].bytes)}.`}
    >
      {items.map((item, i) => {
        const y = i * rowH + 5;
        const barW = (item.bytes / max) * (W - padL - padR);
        const isIndex = item.label !== "chunks" && item.label !== "documents";
        return (
          <g key={item.label}>
            <text x={padL - 8} y={y + 13} className="chartRowLabel" textAnchor="end">
              {item.label}
            </text>
            <rect
              x={padL}
              y={y + 4}
              width={Math.max(1, barW)}
              height={11}
              className={isIndex ? "chartBarIndex" : "chartBar"}
            />
            <text x={W - padR + 8} y={y + 13} className="chartValue">
              {formatBytes(item.bytes)}
            </text>
          </g>
        );
      })}
    </svg>
  );
}